// Prints a Swift source file that embeds the Phosphor fill and duotone icons as JSON.
// Usage: swift GeneratePhosphorCatalog.swift <package/assets directory> <version>
import Foundation

struct IconPaths: Encodable {
    let fill: [String]
    let back: [String]
    let front: [String]
}

struct SVGPath {
    let data: String
    let isTranslucent: Bool
}

final class SVGPathReader: NSObject, XMLParserDelegate {
    private(set) var paths: [SVGPath] = []
    private(set) var unexpectedElement: String?

    func parser(
        _ parser: XMLParser,
        didStartElement elementName: String,
        namespaceURI: String?,
        qualifiedName: String?,
        attributes: [String: String]
    ) {
        switch elementName {
        case "svg":
            break
        case "path":
            paths.append(SVGPath(data: attributes["d"] ?? "", isTranslucent: attributes["opacity"] == "0.2"))
        default:
            unexpectedElement = elementName
            parser.abortParsing()
        }
    }
}

func fail(_ message: String) -> Never {
    FileHandle.standardError.write(Data("error: \(message)\n".utf8))
    exit(1)
}

/// Path data must stay plain so it can't break out of the SVG attribute or the raw string literal.
let pathDataCharacters = CharacterSet(charactersIn: "0123456789.,- eEMmLlHhVvCcSsQqTtAaZz")

func paths(in file: URL) -> [SVGPath] {
    guard let parser = XMLParser(contentsOf: file) else { fail("cannot read \(file.path)") }
    let reader = SVGPathReader()
    parser.delegate = reader
    guard parser.parse() else {
        fail("\(file.lastPathComponent) contains <\(reader.unexpectedElement ?? "invalid XML")>")
    }
    for path in reader.paths where path.data.isEmpty
        || !path.data.unicodeScalars.allSatisfy(pathDataCharacters.contains) {
        fail("\(file.lastPathComponent) has unexpected path data")
    }
    return reader.paths
}

let arguments = CommandLine.arguments.dropFirst()
guard arguments.count == 2, let assetsPath = arguments.first, let version = arguments.last else {
    fail("usage: GeneratePhosphorCatalog.swift <package/assets directory> <version>")
}
let assets = URL(fileURLWithPath: assetsPath)
let fillFiles = try FileManager.default.contentsOfDirectory(atPath: assets.appendingPathComponent("fill").path)
    .filter { $0.hasSuffix("-fill.svg") }

var catalog: [String: IconPaths] = [:]
for fillFile in fillFiles {
    let name = String(fillFile.dropLast("-fill.svg".count))
    guard name.allSatisfy({ $0.isLowercase || $0.isNumber || $0 == "-" }) else {
        fail("unexpected icon name \(name)")
    }
    let fill = paths(in: assets.appendingPathComponent("fill/\(fillFile)"))
    let duotone = paths(in: assets.appendingPathComponent("duotone/\(name)-duotone.svg"))
    catalog[name] = IconPaths(
        fill: fill.map(\.data),
        back: duotone.filter(\.isTranslucent).map(\.data),
        front: duotone.filter { !$0.isTranslucent }.map(\.data)
    )
}
guard catalog.count > 1000 else { fail("found only \(catalog.count) icons in \(assets.path)") }

let encoder = JSONEncoder()
encoder.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
let json = String(decoding: try encoder.encode(catalog), as: UTF8.self)

print("""
// Generated by Scripts/update-phosphor-icons.sh from @phosphor-icons/core \(version). Do not edit.
// Phosphor Icons, MIT License, Copyright (c) 2023 Phosphor Icons. See THIRD-PARTY-NOTICES.md.

extension PhosphorIcon {
    static let catalogJSON = #\"\"\"
\(json)
\"\"\"#
}
""")
